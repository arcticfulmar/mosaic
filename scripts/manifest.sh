#!/usr/bin/env bash
# manifest: mosaic.yaml + mosaic.<env>.yaml → the effective manifest.
#
#   scripts/manifest.sh <env> [project-dir]
#
# Writes the merged manifest to <project-dir>/.mosaic/manifest.<env>.yaml
# and prints that path. bin/mosaic runs this once per invocation when an
# env is selected (`--env <env>` or $MOSAIC_ENV) and exports the path as
# $MOSAIC_MANIFEST; everything downstream reads the manifest through
# lib.sh's manifest_file, so it never knows an env was involved. With no
# env nothing is merged and mosaic.yaml is read as it always was.
#
# This file is the command's own view. The guest's view (what a Lima
# guest's boot-time apply-graft reads) is .mosaic/manifest.yaml, which
# only build, up and reload-web change — bin/mosaic.
#
# An overlay sets only the keys it changes:
#   - maps merge deeply (`ports: {web: 80}` keeps the other ports)
#   - lists and scalars replace (an overlay `plugins:` is the whole list)
#   - `key: null` removes the key, so the base's value gives way to
#     Mosaic's default (`wwwroot: null` → localhost). Only map entries:
#     a null inside a list is just a list element. To make null an
#     ordinary value instead, drop the delpaths() step below.
#
# The merged file goes through every check the base file does (required
# fields, `listen`, the framework map…), because those checks read it.
# Here we only refuse what the merge itself can't make sense of: a
# missing overlay, one that isn't YAML, or one that isn't a mapping.

set -euo pipefail
. "$(dirname "$0")/lib.sh"

env=${1:-}
dir=${2:-.}

[[ -n $env ]] || die "manifest.sh: no env given"
[[ $env =~ ^[A-Za-z0-9][A-Za-z0-9_-]*$ ]] ||
    die "env name '$env' must be letters, digits, '-' or '_' (it names mosaic.$env.yaml)"

base="$dir/mosaic.yaml"
overlay="$dir/mosaic.$env.yaml"
[[ -f $base ]] || die "no mosaic.yaml in $dir"
[[ -f $overlay ]] || die "env '$env' selected but $overlay does not exist"

for f in "$base" "$overlay"; do
    kind=$(yq -r 'tag' "$f" 2>/dev/null) || die "$f is not valid YAML"
    case $kind in
        '!!map') ;;
        # An empty overlay changes nothing; an empty base is caught
        # downstream (no framework:).
        '!!null') ;;
        *) die "$f must be a mapping of keys, not $kind" ;;
    esac
done

mkdir -p "$dir/.mosaic"
out="$dir/.mosaic/manifest.$env.yaml"
tmp=$(mktemp "$dir/.mosaic/.manifest.XXXXXX")

BASE=$base OVERLAY=$overlay MOSAIC_ENV_NAME=$env yq -n '
  (load(strenv(BASE)) // {}) as $base |
  (load(strenv(OVERLAY)) // {}) as $over |
  ($base * $over) |
  delpaths([$over | .. | select(tag == "!!null" and (parent | tag) == "!!map") | path]) |
  . head_comment = "Generated by mosaic from mosaic.yaml + mosaic." + strenv(MOSAIC_ENV_NAME) + ".yaml — do not edit; regenerated on every run."
' > "$tmp" || { rm -f "$tmp"; die "could not merge $overlay into $base"; }
mv "$tmp" "$out"

printf '%s' "$(cd "$dir/.mosaic" && pwd)/manifest.$env.yaml"
